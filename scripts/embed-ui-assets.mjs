import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(scriptDir, "..");
const distDir = resolve(rootDir, "src/ui/web/dist");
const outputFile = resolve(rootDir, "src/ui/server/embedded-assets.generated.ts");

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".mjs": "application/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".map": "application/json",
};

function cacheControl(file) {
  return extname(file).toLowerCase() === ".html" ? "no-store" : "public, max-age=3600";
}

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...walk(fullPath));
    } else if (entry.isFile()) {
      out.push(fullPath);
    }
  }
  return out;
}

function writePlaceholder() {
  const source = `/**
 * Auto-generated by \`scripts/embed-ui-assets.mjs\`.
 * This placeholder keeps local dev working before the first \`build:ui\`.
 */

export type EmbeddedFrontendAsset = {
  contentType: string;
  cacheControl: string;
  bodyBase64: string;
};

export const EMBEDDED_FRONTEND_ASSETS: Record<string, EmbeddedFrontendAsset> = {};
`;
  writeFileSync(outputFile, source);
}

if (!existsSync(distDir)) {
  writePlaceholder();
  console.log("[embed-ui-assets] dist not found, wrote placeholder asset map");
  process.exit(0);
}

const files = walk(distDir).sort();
const assets = files.map((file) => {
  const key = relative(distDir, file).replaceAll("\\", "/");
  const ext = extname(file).toLowerCase();
  return {
    key,
    contentType: MIME[ext] ?? "application/octet-stream",
    cacheControl: cacheControl(file),
    bodyBase64: readFileSync(file).toString("base64"),
  };
});

const assetEntries = assets
  .map(
    (asset) =>
      `  ${JSON.stringify(asset.key)}: {\n` +
      `    contentType: ${JSON.stringify(asset.contentType)},\n` +
      `    cacheControl: ${JSON.stringify(asset.cacheControl)},\n` +
      `    bodyBase64: ${JSON.stringify(asset.bodyBase64)},\n` +
      "  },",
  )
  .join("\n");

const source = `/**
 * Auto-generated by \`scripts/embed-ui-assets.mjs\`.
 * Do not edit by hand.
 */

export type EmbeddedFrontendAsset = {
  contentType: string;
  cacheControl: string;
  bodyBase64: string;
};

export const EMBEDDED_FRONTEND_ASSETS: Record<string, EmbeddedFrontendAsset> = {
${assetEntries}
};
`;

writeFileSync(outputFile, source);
console.log(`[embed-ui-assets] embedded ${assets.length} asset(s)`);
